# Usage: python scripts/gen_theme_palette.py src/index.css > src/styles/theme-palette.css
import re,sys
css=open(sys.argv[1],encoding='utf-8').read()
vals={}
for m in re.finditer(r'--color-([a-z]+)-(\d+):\s*(#[0-9A-Fa-f]{6})',css):
    vals.setdefault(m.group(1),{})[int(m.group(2))]=m.group(3)
def rgb(h): return [int(h[i:i+2],16) for i in (1,3,5)]
def hx(c): return '#'+''.join(f'{max(0,min(255,round(v))):02X}' for v in c)
def mix(a,b,t): a,b=rgb(a),rgb(b); return hx([a[i]*t+b[i]*(1-t) for i in range(3)])
SURF='#0E1424'
SH=[50,100,200,300,400,500,600,700,800,900,950]
ALIAS={'slate':['gray','zinc','neutral','stone'],'violet':['purple','fuchsia'],'sky':['cyan','teal'],'emerald':['green','lime'],'amber':['yellow','orange'],'red':['rose','pink'],'blue':[],'indigo':[]}
dark={'slate':{50:'#0C1222',100:'#131A2C',200:'#1F2840',300:'#2C3651',400:'#6B7692',500:'#8C95AD',600:'#A9B1C6',700:'#C5CBDB',800:'#DDE1EB',900:'#EEF0F6',950:'#F8F9FC'}}
for hue in ['blue','indigo','violet','sky','emerald','amber','red']:
    L=vals[hue]
    dark[hue]={50:mix(L[500],SURF,0.10),100:mix(L[500],SURF,0.17),200:mix(L[500],SURF,0.28),300:mix(L[400],SURF,0.55),
       400:L[400],500:L[500],600:mix(L[600],L[400],0.55),700:L[300],800:L[200],900:L[100],950:L[50]}
def block(src,indent='    '):
    o=[]
    for base,al in ALIAS.items():
        for s in SH:
            o.append(f'{indent}--color-{base}-{s}: {src[base][s]};')
        for a in al:
            for s in SH: o.append(f'{indent}--color-{a}-{s}: var(--color-{base}-{s});')
    return '\n'.join(o)
light={h:vals[h] for h in ALIAS}
# Inverse islands: solid dark or saturated backgrounds keep the light theme's colours inside them.
hues=list(ALIAS)+[a for v in ALIAS.values() for a in v]
sel=[]
for h in hues:
    shades=[800,900,950] if h in ['slate','gray','zinc','neutral','stone'] else [500,600,700,800,900,950]
    for s in shades:
        sel.append(f'.bg-{h}-{s}')
        for a in (80,90,95): sel.append(f'.bg-{h}-{s}\\/{a}')
        sel.append(f'.from-{h}-{s}')
for s in [700,800,900,950]: sel += [f'.bg-navy-{s}', f'.from-navy-{s}']
sel += ['.bg-black','.bg-gray-900','.inverse-island','.hero-brand','.sidebar-surface']
print(f"""/* Generated by scripts/gen_theme_palette.py from the light palette in index.css. Edit the generator, not this block. */
:root.dark {{
  color-scheme: dark;
{block(dark,'  ')}
  --color-canvas: #070B16;
  --border: var(--color-slate-200);
  --card: var(--surface-1);
  --popover: var(--surface-2);
  --shadow-2xs: 0 1px 0 0 rgb(0 0 0 / 0.25);
  --shadow-xs: 0 1px 2px 0 rgb(0 0 0 / 0.35);
  --shadow-sm: 0 1px 2px 0 rgb(0 0 0 / 0.35), 0 1px 3px 0 rgb(0 0 0 / 0.25);
  --shadow-md: 0 2px 4px -1px rgb(0 0 0 / 0.35), 0 4px 12px -2px rgb(0 0 0 / 0.4);
  --shadow-lg: 0 4px 8px -2px rgb(0 0 0 / 0.35), 0 12px 28px -6px rgb(0 0 0 / 0.5);
  --shadow-xl: 0 8px 16px -4px rgb(0 0 0 / 0.4), 0 20px 44px -8px rgb(0 0 0 / 0.55);
  --shadow-2xl: 0 24px 60px -12px rgb(0 0 0 / 0.65);
}}

/* Inside already-dark or saturated panels (code blocks, gradient heroes, solid buttons) keep the light
   theme's colours, so text like text-slate-300 or text-blue-100 stays readable there. */
:where(.dark) :is({', '.join(sel)}) {{
{block(light)}
}}""")
